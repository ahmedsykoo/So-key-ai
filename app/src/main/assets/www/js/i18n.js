window.t = function (key, fallback) {
  // The active language lives in the persisted store (Store.state.settings.lang),
  // anything else is a fallback so that early calls during boot still resolve.
  const lang = (window.Store && window.Store.state && window.Store.state.settings
    && window.Store.state.settings.lang) || "ar";
  const dict = window.I18N[lang] || window.I18N.ar;
  if (dict[key] !== undefined) return dict[key];
  if (window.I18N.ar[key] !== undefined) return window.I18N.ar[key];
  return fallback !== undefined ? fallback : key;
};
